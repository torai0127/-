/**
 * キーワードでFAQを検索
 */
export function searchFAQ(query: string): FAQItem[] {
  const lowerQuery = query.toLowerCase();
  
  return FAQ_DATABASE.filter((item) =>
    item.keywords.some((keyword) => lowerQuery.includes(keyword)) ||
    item.question.toLowerCase().includes(lowerQuery)
  );
}

/**
 * カテゴリでFAQをフィルタ
 */
export function getFAQByCategory(category: string): FAQItem[] {
  return FAQ_DATABASE.filter((item) => item.category === category);
}

/**
 * 全カテゴリを取得
 */
export function getAllCategories(): string[] {
  return [...new Set(FAQ_DATABASE.map((item) => item.category))];
}
